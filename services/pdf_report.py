"""Optional PDF export of a project plan using ReportLab.

ReportLab is imported lazily so the core app still runs if it is not installed.
All AI text is escaped before it goes into ReportLab Paragraphs (which parse markup).
"""
from datetime import date
from io import BytesIO
from xml.sax.saxutils import escape


class PDFUnavailableError(Exception):
    """ReportLab is not installed."""


def is_available():
    try:
        import reportlab  # noqa: F401
    except ImportError:
        return False
    return True


def _num(n, digits=2):
    n = float(n)
    return f"{n:,.0f}" if n == int(n) else f"{n:,.{digits}f}"


def _money(n, cur):
    return f"{cur} {_num(n)}"


def build_pdf(plan, est, mode):
    """Return the PDF report as bytes."""
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import (
            ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
        )
    except ImportError as exc:
        raise PDFUnavailableError("ReportLab is not installed") from exc

    ss = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=ss["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("small", parent=body, fontSize=8, leading=10, textColor=colors.HexColor("#555555"))
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontSize=20, alignment=0, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=13, textColor=colors.HexColor("#3730a3"), spaceBefore=10)
    h3 = ParagraphStyle("h3", parent=ss["Heading4"], fontSize=10, spaceBefore=6, spaceAfter=2)
    warn = ParagraphStyle("warn", parent=body, backColor=colors.HexColor("#fef3c7"),
                          borderColor=colors.HexColor("#f59e0b"), borderWidth=0.5, borderPadding=5)

    def p(text, style=body):
        return Paragraph(escape(str(text or "")), style)

    def bullets(items):
        return ListFlowable([ListItem(p(i), leftIndent=10) for i in items], bulletType="bullet", start="•", leftIndent=12)

    def table(rows, widths, header=True):
        t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
        style = [
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d1d5db")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("FONTSIZE", (0, 0), (-1, -1), 9),
        ]
        if header:
            style.append(("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2ff")))
        t.setStyle(TableStyle(style))
        return t

    cur = est["currency"]
    title = plan.get("user_title") or plan["project_title"]
    story = [p(title, h1),
             p(f"{plan['project_category']} · Generated by ProjectScope on {date.today().isoformat()} · "
               + ("DEMO SAMPLE" if mode == "demo" else "AI-generated plan"), small),
             Spacer(1, 6)]
    if mode == "demo":
        story += [p("DEMO MODE: this is a fixed sample plan, not AI-generated output, and it does not "
                    "reflect the submitted idea. Only the calculation inputs were applied.", warn), Spacer(1, 6)]

    # A. Overview
    story += [p("Project Overview", h2), p(plan["project_summary"]),
              p("Problem statement", h3), p(plan["problem_statement"])]
    for label, key in [("Target users", "target_users"), ("Objectives", "objectives"),
                       ("Requirements", "requirements"), ("Assumptions", "assumptions"),
                       ("Missing information that may change the estimate", "missing_information")]:
        if plan.get(key):
            story += [p(label, h3), bullets(plan[key])]

    # D. Estimation summary
    story += [p("Estimation Summary (approximate)", h2)]
    rows = [
        ["Total development hours", f"{_num(est['total_hours'])} h"],
        ["Estimated duration", f"{est['duration_weeks']} week(s) ({_num(est['duration_weeks_exact'])} exact)"],
        ["Team", f"{est['team_size']} developer(s) × {_num(est['weekly_hours'])} h/week"],
        ["Hourly rate", _money(est["hourly_rate"], cur)],
        ["Base development cost", _money(est["base_cost"], cur)],
        [f"Contingency ({_num(est['contingency_percent'])}%)", _money(est["contingency_amount"], cur)],
        ["Estimated total budget", _money(est["total_budget"], cur)],
        ["Confidence", plan["confidence"].capitalize()],
    ]
    t = table(rows, [70 * mm, 100 * mm], header=False)
    t.setStyle(TableStyle([("FONTNAME", (0, 6), (-1, 6), "Helvetica-Bold"),
                           ("BACKGROUND", (0, 6), (-1, 6), colors.HexColor("#eef2ff"))]))
    story += [t, Spacer(1, 4),
              p("Confidence reflects how clear the requirements are. It is not a statistical probability of accuracy.", small),
              p(est["duration_caveat"], small), p(est["budget_note"], small)]

    story += [p("Task estimates", h3)]
    rows = [["Task", "Description", "Hours"]]
    rows += [[p(t["name"]), p(t["description"], small), _num(t["hours"])] for t in plan["task_estimates"]]
    rows.append(["Total", "", _num(est["total_hours"])])
    t = table(rows, [50 * mm, 100 * mm, 20 * mm])
    t.setStyle(TableStyle([("ALIGN", (2, 0), (2, -1), "RIGHT"), ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold")]))
    story.append(t)

    # B. Features
    story += [p("Feature Breakdown", h2)]
    for label, cat in [("MVP features", "mvp"), ("Future / advanced features", "future")]:
        feats = [f for f in plan["features"] if (f["category"] == "mvp") == (cat == "mvp")]
        story.append(p(label, h3))
        if not feats:
            story.append(p("None listed.", small))
            continue
        rows = [["Feature", "Priority", "Est. hours"]]
        rows += [[[p(f["name"]), p(f["description"], small)], f["priority"].capitalize(),
                  "-" if f["hours"] is None else _num(f["hours"])] for f in feats]
        story.append(table(rows, [120 * mm, 25 * mm, 25 * mm]))
    story.append(p("Feature hours are indicative only. Totals come from the task breakdown.", small))

    # C. Tech stack
    story += [p("Recommended Technology Stack", h2)]
    rows = [["Technology", "Category", "Reason"]]
    rows += [[p(t["name"]), p(t["category"]), p(t["reason"], small)] for t in plan["technology_stack"]]
    story.append(table(rows, [40 * mm, 30 * mm, 100 * mm]))

    # E. Roadmap
    story += [p("Development Roadmap", h2)]
    rows = [["#", "Stage", "Priority", "Depends on"]]
    rows += [[str(r["sequence"]), [p(r["title"]), p(r["description"], small)], r["priority"].capitalize(),
              p(", ".join(r["dependencies"]) or "-", small)] for r in plan["roadmap"]]
    story.append(table(rows, [10 * mm, 105 * mm, 20 * mm, 35 * mm]))

    # F. Risks
    story += [p("Risk Analysis", h2)]
    rows = [["Risk", "Severity", "Mitigation"]]
    rows += [[p(r["description"]), r["severity"].capitalize(), p(r["mitigation"] or "-", small)] for r in plan["risks"]]
    story.append(table(rows, [70 * mm, 20 * mm, 80 * mm]))

    story += [Spacer(1, 10), p("ProjectScope · All estimates are approximate and for planning only.", small)]

    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm, title=title, author="ProjectScope")
    doc.build(story)
    return buf.getvalue()
